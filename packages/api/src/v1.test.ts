// Every procedure of a router, by its key. A part of the router that is loaded only when it is
// called is loaded here, so that it hides nothing.
async function proceduresOf(router: object, path: string[] = []): Promise<string[]> {
  const found: string[] = [];
  for (const [key, value] of Object.entries(router)) {
    const node: object = isLazy(value) ? (await unlazy(value)).default : value;
    if (isProcedure(node)) found.push([...path, key].join("."));
    else found.push(...(await proceduresOf(node, [...path, key])));
  }
  return found;
}

const procedures = await proceduresOf(v1Router);

describe("version 1 of the API", () => {
  it("keeps every procedure it ever had", () => {
    const gone = V1_PROCEDURES.filter((name) => !procedures.includes(name));
    expect(gone, "a procedure of v1 that goes away goes in a new version").toEqual([]);
  });

  it("names each new procedure in the list, which then keeps it", () => {
    const unlisted = procedures.filter((name) => !V1_PROCEDURES.includes(name));
    expect(unlisted, "a new procedure of v1 adds its key to V1_PROCEDURES").toEqual([]);
  });
});
